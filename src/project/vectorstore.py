import json
from json import JSONDecodeError

from langchain_community.vectorstores import FAISS
from project.loader import load_documents
from project.embeddings import get_embedding_model, get_embeddings
from project.config import INDEX_PATH, get_provider


def get_index_provider_metadata():
    return {
        "provider": get_provider(),
        "embedding_model": get_embedding_model(),
    }


def _read_and_validate_metadata():
    metadata_path = INDEX_PATH / "index_metadata.json"
    if not metadata_path.is_file():
        raise ValueError(
            "The FAISS index is missing index_metadata.json and cannot be verified. "
            "Rebuild it with "
            "python -c \"from project.vectorstore import build_vectorstore; build_vectorstore()\""
        )

    try:
        metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
    except (OSError, JSONDecodeError) as exc:
        raise ValueError(
            f"Unable to read FAISS index metadata at {metadata_path}. Rebuild the index."
        ) from exc

    if not isinstance(metadata, dict) or not isinstance(metadata.get("provider"), str) or not isinstance(
        metadata.get("embedding_model"), str
    ):
        raise ValueError(
            "FAISS index_metadata.json is invalid or incomplete. Rebuild the index."
        )

    current = get_index_provider_metadata()
    if metadata != current:
        raise ValueError(
            "The FAISS index was built with a different embedding provider or model "
            f"(index: {metadata}; current: {current}). Rebuild it with "
            "python -c \"from project.vectorstore import build_vectorstore; build_vectorstore()\""
        )


def build_vectorstore():
    documents = load_documents()
    if not documents:
        raise ValueError("The academic paper dataset is empty.")

    db = FAISS.from_documents(documents, get_embeddings())
    INDEX_PATH.mkdir(parents=True, exist_ok=True)
    db.save_local(str(INDEX_PATH))
    (INDEX_PATH / "index_metadata.json").write_text(
        json.dumps(get_index_provider_metadata(), indent=2),
        encoding="utf-8",
    )

    return db


def load_vectorstore():
    if not INDEX_PATH.joinpath("index.faiss").is_file() or not INDEX_PATH.joinpath("index.pkl").is_file():
        raise FileNotFoundError(
            "The FAISS index is missing. Build it with "
            "python -c \"from project.vectorstore import build_vectorstore; build_vectorstore()\""
        )

    _read_and_validate_metadata()

    return FAISS.load_local(
        str(INDEX_PATH),
        get_embeddings(),
        # index.pkl is a trusted file generated by build_vectorstore(). Never
        # enable this option for an index obtained from an untrusted source.
        allow_dangerous_deserialization=True,
    )


def get_distinct_paper_count(db):
    paper_ids = {
        str(document.metadata.get("paper_id") or document.metadata.get("title") or "").strip()
        for document in db.docstore._dict.values()
    }
    return len(paper_ids - {""})